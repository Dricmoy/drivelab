test('model training displays measured errors and enables learned planner runs', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await openWorkspace(page);
  const cvResponse = page.waitForResponse(r => r.url().endsWith('/api/runs') && r.request().method() === 'POST');
  await page.getByRole('button', { name: /Turning traffic/ }).click();
  const cvReport = await (await cvResponse).json();
  await expect(page.getByRole('button', { name: 'Run planner', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'Model', exact: true }).click();
  await page.getByLabel('Training seed').fill('42');
  await page.getByLabel('Training epochs').selectOption('80');
  const trainingResponse = page.waitForResponse(r => r.url().endsWith('/api/model/train'));
  await page.getByRole('button', { name: 'Train on synthetic motion', exact: true }).click();
  const response = await trainingResponse;
  expect(response.status()).toBe(200);
  const model = await response.json();
  expect(model.source).toBe('synthetic-motion');
  expect(model.metrics.learned_ade).toBeLessThan(model.metrics.baseline_ade);
  expect(model.metrics.learned_fde).toBeLessThan(model.metrics.baseline_fde);
  await expect(page.locator('.model-error-table')).toContainText(model.metrics.learned_ade.toFixed(2));
  await expect(page.locator('.model-facts')).toContainText('256');
  await page.screenshot({ path: 'test-results/model-desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'Use learned forecasting', exact: true }).click();
  const runResponse = page.waitForResponse(r => r.url().endsWith('/api/runs') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Run planner', exact: true }).click();
  const report = await (await runResponse).json();
  expect(report.config.prediction).toBe('learned');
  expect(report.frames[0].explanation.toLowerCase()).toContain('learned');
  expect(report.engine).toMatch(/waymax/);
  expect(report.frames[0].candidates).toEqual(cvReport.frames[0].candidates);
  expect(report.frames[20].candidates).not.toEqual(cvReport.frames[20].candidates);
  expect(report.frames[20].actor_forecasts).not.toEqual(cvReport.frames[20].actor_forecasts);
  await page.getByLabel('Replay timeline').fill('20');
  const forecast = report.frames[20].actor_forecasts[0];
  const overlay = page.locator(`[data-forecast-actor="${forecast.actor_id}"]`);
  await expect(overlay).toHaveAttribute('points', forecast.points.map((p: number[]) => p.join(',')).join(' '));
  await page.getByLabel('Traffic forecasts', { exact: true }).uncheck();
  await expect(overlay).toHaveCount(0);
  await page.getByLabel('Traffic forecasts', { exact: true }).check();
  await expect(overlay).toBeVisible();
  await expect(page.locator('.run-receipt')).toContainText(report.id.slice(0, 8));
  expect(errors).toEqual([]);
  await page.getByRole('button', { name: 'Model', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/model-mobile.png', fullPage: true });
});

