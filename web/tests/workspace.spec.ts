  // center the replay below a large blank region or move the history controls.
  const heading = await page.getByRole('heading', { name: 'Parked car', exact: true }).boundingBox();
  expect(heading!.y).toBeLessThan(260);
  await expect(page.getByRole('button', { name: 'Saved runs', exact: true })).toBeInViewport();
