test('baseline failure, parameter changes and saved run restore are functional', async ({ page }) => {
  await openWorkspace(page);
  await page.getByLabel('Planner', { exact: true }).selectOption('baseline');
  const response = page.waitForResponse(r => r.url().endsWith('/api/runs') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Run planner', exact: true }).click();
  const baseline = await (await response).json();
  expect(baseline.metrics.collision).toBe(true);
  await expect(page.locator('.run-status')).toContainText('Failure recorded');
  await page.getByRole('button', { name: 'Inspect first failure', exact: true }).click();
  await expect(page.locator('.time-display strong')).not.toHaveText('0.0s');
  await page.getByRole('button', { name: 'Configure', exact: true }).click();
  await page.getByLabel('Target speed', { exact: true }).fill('4');
  await page.getByRole('button', { name: 'Apply settings', exact: true }).click();
  const changedResponse = page.waitForResponse(r => r.url().endsWith('/api/runs') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Run planner', exact: true }).click();
  const changed = await (await changedResponse).json();
  expect(changed.config.target_speed).toBe(4);
  expect(changed.metrics.mean_speed).toBeLessThan(baseline.metrics.mean_speed);
  await page.getByRole('button', { name: /Clear road/ }).click();
  await expect(page.getByRole('button', { name: 'Run planner', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'Saved runs', exact: true }).click();
  await page.locator('.history-list button').filter({ hasText: 'Parked car' }).first().click();
  await expect(page.getByRole('heading', { name: 'Parked car', exact: true })).toBeVisible();
  await expect(page.locator('.run-receipt')).toContainText(changed.id.slice(0, 8));
});

